def parse_final_metrics() -> pd.DataFrame:
    rows = []
    for path in LOGS:
        text = path.read_text(errors="replace")
        horizon = None
        model = None
        config = None
        lines = text.splitlines()
        i = 0
        while i < len(lines):
            m = re.match(r"Final test: H=(\d+)m", lines[i])
            if m:
                horizon = int(m.group(1))
            m = re.match(r"Final model=([^,]+), config=([^,]+), H=(\d+)m", lines[i])
            if m:
                model, config, horizon = m.group(1), m.group(2), int(m.group(3))
            if lines[i].strip() == "Metrics: {" and model is not None:
                block = ["{"]
                i += 1
                while i < len(lines):
                    block.append(lines[i])
                    if lines[i].strip() == "}":
                        break
                    i += 1
                metrics = json.loads("\n".join(block))
                rows.append({"horizon_month": horizon, "model_name": model, "config_name": config, **metrics})
            i += 1
    df = pd.DataFrame(rows).drop_duplicates(["horizon_month", "model_name"], keep="last")
    df = df[df.model_name.isin(MODEL_ORDER) & df.horizon_month.isin(HORIZONS)].copy()
    df.to_csv(TAB / "final_model_metrics_282.csv", index=False)
    return df


