def ablation_summary() -> tuple[pd.DataFrame, pd.DataFrame]:
    df = pd.read_csv(ABLATION / "ablation_final_test_metrics.csv")
    base = df[df.feature_set_name.eq("full_features")][
        ["horizon_month", "model_name", "precision", "recall", "f1", "pr_auc", "auc", "brier"]
    ]
    base = base.rename(columns={c: f"base_{c}" for c in ["precision", "recall", "f1", "pr_auc", "auc", "brier"]})
    d = df.merge(base, on=["horizon_month", "model_name"], how="left")
    for metric in ["precision", "recall", "f1", "pr_auc", "auc", "brier"]:
        d[f"delta_{metric}"] = d[metric] - d[f"base_{metric}"]
    order = ["only_top1_groups", "only_top2_groups", "only_top3_groups", "remove_top1_groups", "remove_top2_groups", "remove_top3_groups"]
    labels = ["Only top 1", "Only top 2", "Only top 3", "Remove top 1", "Remove top 2", "Remove top 3"]
    summary = d[d.feature_set_name.isin(order)].groupby("feature_set_name").agg(
        delta_precision=("delta_precision", "mean"), delta_recall=("delta_recall", "mean"),
        delta_f1=("delta_f1", "mean"), delta_pr_auc=("delta_pr_auc", "mean"),
        delta_auc=("delta_auc", "mean"), delta_brier=("delta_brier", "mean"),
        mean_n_features=("n_features", "mean"),
    ).reindex(order).reset_index()
    summary.to_csv(TAB / "ablation_mean_deltas.csv", index=False)
    horizon_summary = (
        d[d.feature_set_name.isin(order)]
        .groupby(["horizon_month", "feature_set_name"])
        .agg(
            delta_precision=("delta_precision", "mean"),
            delta_recall=("delta_recall", "mean"),
            delta_f1=("delta_f1", "mean"),
            delta_auc=("delta_auc", "mean"),
            mean_n_features=("n_features", "mean"),
        )
        .reset_index()
    )
    horizon_summary.to_csv(TAB / "ablation_deltas_by_horizon.csv", index=False)
    d[d.feature_set_name.isin(order)].to_csv(TAB / "ablation_deltas_by_model_horizon.csv", index=False)
    return d, summary


def paired_ablation_bars(
    ax: plt.Axes,
    summary: pd.DataFrame,
    metric: str,
    ylabel: str,
    letter: str,
    annotate: bool = True,
) -> None:
    x = np.arange(3)
    retain = summary.set_index("feature_set_name").loc[
        ["only_top1_groups", "only_top2_groups", "only_top3_groups"], metric
    ].to_numpy()
    remove = summary.set_index("feature_set_name").loc[
        ["remove_top1_groups", "remove_top2_groups", "remove_top3_groups"], metric
    ].to_numpy()
    width = 0.40
    bars_retain = ax.bar(
        x - width / 2, retain, width, color=RETAIN_COLOR, edgecolor="white",
        linewidth=0.5, label="Retain only",
    )
    bars_remove = ax.bar(
        x + width / 2, remove, width, color=REMOVE_COLOR, edgecolor="white",
        linewidth=0.5, hatch="//", label="Remove",
    )
    ax.axhline(0, color="0.18", lw=0.8)
    ax.set(xticks=x, xticklabels=["Top 1", "Top 2", "Top 3"], ylabel=ylabel)
    style_panel_label(ax, letter)
    style_axes(ax)
    ax.grid(axis="y", color="0.91", lw=0.55)
    all_values = np.concatenate([retain, remove, [0]])
    data_span = float(all_values.max() - all_values.min()) or 0.01
    ax.set_ylim(all_values.min() - 0.12 * data_span, all_values.max() + 0.18 * data_span)
    offset = 0.025 * data_span
    value_format = "+.4f" if metric == "delta_auc" else "+.3f"
    if annotate:
        for bars in [bars_retain, bars_remove]:
            for bar in bars:
                value = bar.get_height()
                ax.text(
                    bar.get_x() + bar.get_width() / 2,
                    value + (offset if value >= 0 else -offset),
                    format(value, value_format), ha="center",
                    va="bottom" if value >= 0 else "top", fontsize=ANNOTATION_SIZE,
                )


def overlay_horizon_ablation(
    ax: plt.Axes,
    d: pd.DataFrame,
    metric: str,
    *,
    marker_size: float = 16,
) -> None:
    means = d.groupby(["horizon_month", "feature_set_name"])[metric].mean()
    width = 0.40
    for i in range(3):
        retain_name = f"only_top{i + 1}_groups"
        remove_name = f"remove_top{i + 1}_groups"
        for horizon in HORIZONS:
            for xpos, name in [(i - width / 2, retain_name), (i + width / 2, remove_name)]:
                ax.scatter(
                    xpos, means.loc[(horizon, name)], marker=HORIZON_MARKERS[horizon],
                    s=marker_size, facecolor="white", edgecolor="0.15",
                    linewidth=0.65, zorder=5,
                )
    ymin, ymax = ax.get_ylim()
    values = means.to_numpy()
    lower = min(ymin, float(values.min()))
    upper = max(ymax, float(values.max()))
    span = upper - lower or 0.01
    ax.set_ylim(lower - 0.04 * span, upper + 0.08 * span)


