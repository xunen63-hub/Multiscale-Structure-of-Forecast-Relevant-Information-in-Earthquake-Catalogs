    style_axes(ax_structure)
    ax_structure.set_xticks([0.5, 3.5, 6.5, 9.5, 11.5])
    ax_structure.set_xticklabels(["-12", "-9", "-6", "-3", "-1"], rotation=0)
    ax_structure.tick_params(axis="y", labelrotation=0)

