def ranked_overlap(feature_df: pd.DataFrame, item_col: str, max_k: int) -> pd.DataFrame:
    rows = []
    for h in HORIZONS:
        by_model = {}
        for model in ["CatBoost", "ExtraTrees", "XGBoost"]:
            d = feature_df[(feature_df.horizon_month == h) & (feature_df.model_name == model)].sort_values("rank")
            by_model[model] = d[item_col].astype(str).tolist()
        for k in range(1, max_k + 1):
            sets = {m: set(v[:k]) for m, v in by_model.items()}
            pair = [len(sets[a] & sets[b]) / k for a, b in combinations(sets, 2)]
            all3 = len(set.intersection(*sets.values())) / k
            rows.append({"horizon_month": h, "top_k": k, "pairwise_mean": np.mean(pair), "all_three": all3})
    return pd.DataFrame(rows)


def rank_spearman(feature_df: pd.DataFrame, item_col: str, score_col: str) -> pd.DataFrame:
    rows = []
    for h in HORIZONS:
        pivot = feature_df[feature_df.horizon_month.eq(h)].pivot(index=item_col, columns="model_name", values=score_col)
        for a, b in combinations(["CatBoost", "ExtraTrees", "XGBoost"], 2):
            rho = spearmanr(pivot[a], pivot[b]).statistic
            rows.append({"horizon_month": h, "model_pair": f"{a}–{b}", "rho": rho})
    return pd.DataFrame(rows)


def monthly_extreme_structure() -> tuple[pd.DataFrame, dict[int, pd.DataFrame]]:
    """Arrange true-positive monthly-extreme SHAP on chronological windows."""
    features_all = pd.read_csv(SHAP / "all_shap_feature_importance.csv")
    structure = features_all[
        features_all.subset_name.eq("true_positive")
        & features_all.feature_group.eq("monthly_lag/magnitude_extreme")
        & features_all.horizon_month.isin([1, 12])
    ].copy()
    structure["group_abs"] = structure.groupby(
        ["model_name", "horizon_month"]
    ).mean_abs_shap.transform("sum")
    structure["signed_within_group"] = structure.mean_signed_shap / structure.group_abs
    structure["magnitude_order"] = structure.feature_name.str.extract(r"top(\d+)_").astype(int)
    structure_mean = (
        structure.groupby(["horizon_month", "month_lag", "magnitude_order"])["signed_within_group"]
        .mean().reset_index()
    )
    pivots = {}
    for horizon in [1, 12]:
        pivot = (
            structure_mean[structure_mean.horizon_month.eq(horizon)]
            .pivot(index="magnitude_order", columns="month_lag", values="signed_within_group")
            .reindex(index=range(1, 6), columns=range(12, 0, -1))
        )
        pivot.columns = list(range(-12, 0))
        pivots[horizon] = pivot
    return structure_mean, pivots


