def write_key_numbers() -> None:
    features, groups = all_test_shap()
    feat20 = ranked_overlap(features, "feature_name", 20)
    grp10 = ranked_overlap(groups, "group_name", 10)
    stable = []
    for group in sorted(groups.group_name.unique()):
        occurrences = 0
        for (h, model), d in groups.groupby(["horizon_month", "model_name"]):
            occurrences += int(group in set(d.nsmallest(10, "rank").group_name))
        stable.append({"group_name": group, "top10_occurrences_of_12": occurrences})
    pd.DataFrame(stable).sort_values("top10_occurrences_of_12", ascending=False).to_csv(TAB / "stable_group_occurrence.csv", index=False)
    summary = {
        "top20_feature_pairwise_overlap_by_horizon": feat20[feat20.top_k.eq(20)].set_index("horizon_month").pairwise_mean.to_dict(),
        "top20_feature_all3_overlap_by_horizon": feat20[feat20.top_k.eq(20)].set_index("horizon_month").all_three.to_dict(),
        "top10_group_pairwise_overlap_by_horizon": grp10[grp10.top_k.eq(10)].set_index("horizon_month").pairwise_mean.to_dict(),
        "top10_group_all3_overlap_by_horizon": grp10[grp10.top_k.eq(10)].set_index("horizon_month").all_three.to_dict(),
    }
    (TAB / "key_numbers.json").write_text(json.dumps(summary, indent=2))

    meta = pd.read_csv(FEATURE_META)
    meta["feature_group"] = meta["time_group"].astype(str) + "/" + meta["signal_group"].astype(str)
    core_groups = [
        "monthly_lag/magnitude_extreme",
        "annual/magnitude_extreme",
        "last100/temporal_clustering",
    ]
    core74 = meta[meta["feature_group"].isin(core_groups)].sort_values("feature_idx").copy()
    if len(core74) != 74:
        raise ValueError(f"Expected 74 core features, found {len(core74)}")
    core74.insert(0, "core_order", np.arange(1, len(core74) + 1))
    core74.to_csv(TAB / "core_74_features_H6_H12.csv", index=False)
    (TAB / "core_74_feature_names.txt").write_text("\n".join(core74["feature_name"].tolist()) + "\n")


