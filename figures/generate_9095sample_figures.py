def figure4_ablation_rows() -> pd.DataFrame:
    """Return model-level frozen-group retention and removal comparisons."""
    discovery = pd.read_csv(ABLATION / "ablation_deltas_vs_full.csv")
    heldout = pd.read_csv(HELDOUT_ABLATION / "heldout_deltas_vs_full.csv")

    discovery_retain = discovery[
        discovery.feature_set_name.eq("only_top3_groups")
    ].copy()
    heldout_retain = heldout[
        heldout.feature_set_type.eq("retain_only")
        & heldout.top_k_groups.eq(3)
    ].copy()
    discovery_remove = discovery[
        discovery.feature_set_type.eq("remove_top_groups")
    ].copy()
    heldout_remove = heldout[
        heldout.feature_set_type.eq("remove")
    ].copy()

    frames = []
    for role, retain, remove in [
        ("Discovery architectures", discovery_retain, discovery_remove),
        ("Held-out architectures", heldout_retain, heldout_remove),
    ]:
        retain = retain.copy()
        retain["architecture_role"] = role
        retain["comparison"] = "Retain compact core"
        frames.append(retain)

        remove = remove.copy()
        remove["architecture_role"] = role
        remove["comparison"] = "Remove"
        frames.append(remove)

    return pd.concat(frames, ignore_index=True, sort=False)


