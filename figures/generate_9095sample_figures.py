def add_horizon_points(
    ax: plt.Axes,
    x_center: float,
    values: pd.Series,
    *,
    size: float = 20,
) -> None:
    offsets = {1: -0.075, 3: -0.025, 6: 0.025, 12: 0.075}
    for horizon in HORIZONS:
        ax.scatter(
            x_center + offsets[horizon],
            float(values.loc[horizon]),
            marker=HORIZON_MARKERS[horizon],
            s=size,
            facecolor="white",
            edgecolor="0.15",
            linewidth=0.7,
            zorder=5,
        )


def add_model_horizon_points(
    ax: plt.Axes,
    x_center: float,
    data: pd.DataFrame,
    model_order: list[str],
    *,
    size: float = 17,
) -> None:
    """Plot every model result while retaining the horizon marker encoding."""
    horizon_offsets = {1: -0.090, 3: -0.030, 6: 0.030, 12: 0.090}
    if len(model_order) == 3:
        model_offsets = np.array([-0.013, 0.0, 0.013])
    elif len(model_order) == 2:
        model_offsets = np.array([-0.009, 0.009])
    else:
        model_offsets = np.linspace(-0.012, 0.012, len(model_order))

    for horizon in HORIZONS:
        horizon_data = (
            data[data.horizon_month.eq(horizon)]
            .set_index("model_name")
            .reindex(model_order)
        )
        if horizon_data["delta_auc_vs_full"].isna().any():
            raise ValueError(
                f"Missing Figure 4 model point(s) for H{horizon}: "
                + ", ".join(
                    horizon_data.index[
                        horizon_data["delta_auc_vs_full"].isna()
                    ].astype(str)
                )
            )
        ax.scatter(
            x_center + horizon_offsets[horizon] + model_offsets,
            horizon_data["delta_auc_vs_full"].to_numpy(),
            marker=HORIZON_MARKERS[horizon],
            s=size,
            facecolor="white",
            edgecolor="0.42",
            linewidth=0.55,
            alpha=0.78,
            zorder=5,
        )


def add_overall_mean_sd(
    ax: plt.Axes,
    x_center: float,
    values: np.ndarray,
    *,
    mean: float,
    marker_size: float = 4.7,
) -> None:
    """Add a black overall-mean diamond with descriptive ±1 SD whiskers."""
    clean = np.asarray(values, dtype=float)
    clean = clean[np.isfinite(clean)]
    spread = float(np.std(clean, ddof=1)) if clean.size > 1 else 0.0
    ax.errorbar(
        x_center,
        mean,
        yerr=spread,
        fmt="D",
        markersize=marker_size,
        markerfacecolor="0.08",
        markeredgecolor="white",
        markeredgewidth=0.40,
        color="0.08",
        elinewidth=0.75,
        capsize=2.0,
        capthick=0.75,
        zorder=7,
    )


