def topk_innerfrozen_summary() -> pd.DataFrame:
    """Parse the archived leakage-controlled Top-K summary log."""
    if not TOPK_INNER_LOG.exists():
        raise FileNotFoundError(TOPK_INNER_LOG)

    lines = TOPK_INNER_LOG.read_text(encoding="utf-8").splitlines()
    start = next(
        (i for i, line in enumerate(lines) if line.strip().startswith("topk ")),
        None,
    )
    if start is None:
        raise ValueError(f"Top-K result table not found in {TOPK_INNER_LOG}")
    end = next(
        (i for i in range(start + 1, len(lines)) if not lines[i].strip()),
        len(lines),
    )
    result = pd.read_csv(
        StringIO("\n".join(lines[start:end])), sep=r"\s+",
    )
    required = {
        "topk", "horizon_month", "n_features",
        "delta_auc_minus_full", "delta_pr_auc_minus_full",
        "delta_f1_minus_full", "delta_brier_minus_full",
        "stable_all_metrics",
    }
    missing = required - set(result.columns)
    if missing:
        raise ValueError(
            "Top-K summary is missing columns: " + ", ".join(sorted(missing))
        )
    result = result.sort_values(["topk", "horizon_month"]).reset_index(drop=True)
    expected = pd.MultiIndex.from_product(
        [[25, 50, 75, 100], HORIZONS], names=["topk", "horizon_month"],
    )
    observed = pd.MultiIndex.from_frame(result[["topk", "horizon_month"]])
    if not observed.equals(expected):
        raise ValueError(
            "Top-K log does not contain the expected 4 K values x 4 horizons."
        )
    result.to_csv(
        TAB / "topk_innerfrozen_consensus_summary.csv", index=False,
    )
    return result


