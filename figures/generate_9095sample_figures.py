def read_map_events(retained_regions: set[str]) -> tuple[pd.DataFrame, pd.DataFrame]:
    background_parts = []
    target_parts = []
    for i, chunk in enumerate(pd.read_csv(
        CATALOG,
        usecols=["lat", "lng", "magnitude", "region"],
        chunksize=200_000,
    )):
        chunk["region"] = chunk["region"].map(normalize_region)
        chunk = chunk[chunk.region.isin(retained_regions)]
        background = chunk[chunk.magnitude.lt(5)]
        if not background.empty:
            background_parts.append(
                background.sample(n=min(450, len(background)), random_state=1701 + i)
            )
        target_parts.append(chunk[chunk.magnitude.ge(5)])
    return pd.concat(background_parts, ignore_index=True), pd.concat(target_parts, ignore_index=True)


def add_design_box(
    ax: plt.Axes,
    xy: tuple[float, float],
    width: float,
    height: float,
    text_value: str,
    facecolor: str,
    edgecolor: str,
    fontsize: float = 6.1,
) -> None:
    box = FancyBboxPatch(
        xy, width, height, boxstyle="round,pad=0.012,rounding_size=0.014",
        facecolor=facecolor, edgecolor=edgecolor, linewidth=0.8,
        transform=ax.transAxes,
    )
    ax.add_patch(box)
    ax.text(
        xy[0] + width / 2, xy[1] + height / 2, text_value,
        ha="center", va="center", fontsize=fontsize, transform=ax.transAxes,
    )


