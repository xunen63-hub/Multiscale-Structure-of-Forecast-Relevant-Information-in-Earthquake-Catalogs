def normalize_region(value: str) -> str:
    nums = re.findall(r"-?\d+", str(value))
    return f"[{int(nums[0])}, {int(nums[1])}]" if len(nums) >= 2 else str(value)


def read_catalog_summary(
    retained_regions: set[str] | None = None,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    annual_parts = []
    region_parts = []
    region_year_parts = []
    region_mag_parts = []
    year_mag_parts = []
    mag_labels = ["m_lt3", "m_3_5", "m_5_7", "m_ge7"]
    for chunk in pd.read_csv(
        CATALOG,
        usecols=["date_time", "magnitude", "region"],
        parse_dates=["date_time"],
        chunksize=200_000,
    ):
        chunk["year"] = chunk["date_time"].dt.year
        chunk["magnitude_bin"] = pd.cut(
            chunk["magnitude"], bins=[-np.inf, 3, 5, 7, np.inf],
            labels=mag_labels, right=False,
        )
        annual_parts.append(
            chunk.groupby("year").agg(events=("magnitude", "size"), m5_events=("magnitude", lambda x: int((x >= 5).sum())))
        )
        chunk["region"] = chunk["region"].map(normalize_region)
        region_parts.append(chunk.groupby("region").size().rename("events"))
        region_year_parts.append(chunk.groupby(["region", "year"]).size().rename("events"))
        retained = chunk if retained_regions is None else chunk[chunk["region"].isin(retained_regions)]
        region_mag_parts.append(
            retained.groupby(["region", "magnitude_bin"], observed=True).size().rename("events")
        )
        year_mag_parts.append(
            retained.groupby(["year", "magnitude_bin"], observed=True).size().rename("events")
        )
    annual = pd.concat(annual_parts).groupby(level=0).sum().reset_index()
    regions = pd.concat(region_parts).groupby(level=0).sum().rename("events").reset_index()
    region_year = pd.concat(region_year_parts).groupby(level=[0, 1]).sum().rename("events").reset_index()
    region_mag = pd.concat(region_mag_parts).groupby(level=[0, 1], observed=True).sum().rename("events").reset_index()
    year_mag = pd.concat(year_mag_parts).groupby(level=[0, 1], observed=True).sum().rename("events").reset_index()
    annual.to_csv(TAB / "catalog_annual_counts.csv", index=False)
    regions.to_csv(TAB / "catalog_region_counts.csv", index=False)
    region_year.to_csv(TAB / "catalog_region_year_counts.csv", index=False)
    region_mag.to_csv(TAB / "catalog_region_magnitude_counts.csv", index=False)
    year_mag.to_csv(TAB / "catalog_year_magnitude_counts.csv", index=False)
    return annual, regions, region_year, region_mag, year_mag


